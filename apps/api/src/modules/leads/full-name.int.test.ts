import { eq, sql } from 'drizzle-orm';
import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import type { LeadInput } from '@mms/shared';
import { leads } from '../../db/schema/index.ts';
import { loadLegacySeedInput, seed } from '../../db/seed.ts';
import { createTestDb, truncateAll } from '../../test/db.ts';
import { allPermissions, fakeContext, fakeUser } from '../../test/fakes.ts';
import { appRouter } from '../../trpc/router.ts';
import { createCallerFactory } from '../../trpc/trpc.ts';
import { upsertUser } from '../../users/upsert-user.ts';
import { leadRow } from './router.ts';

const createCaller = createCallerFactory(appRouter);

// leads.full_name is generated by the database from first_name and last_name. Nothing may write
// it: the database refuses, and the code never tries.
describe('leads.full_name (generated column)', () => {
  const db = createTestDb();
  let userId = '';

  beforeEach(async () => {
    await truncateAll(db);
    await seed(db, await loadLegacySeedInput());
    ({ id: userId } = await upsertUser(
      db,
      { email: 'micky@makemysolar.com.au', name: 'Micky', roleKey: 'admin' },
      'makemysolar.com.au',
    ));
  });
  afterAll(() => db.$client.end());

  const api = () =>
    createCaller(
      fakeContext(
        {
          status: 'authenticated',
          user: fakeUser({ id: userId, permissions: allPermissions() }),
          firebaseUid: 'uid',
        },
        { db },
      ),
    );

  const fullNameOf = async (id: string) =>
    (await db.select({ fullName: leads.fullName }).from(leads).where(eq(leads.id, id)))[0]
      ?.fullName;

  const olivia: LeadInput = {
    firstName: 'Olivia',
    lastName: 'Nguyen',
    mobile: '0412 345 678',
  };

  it('is filled in when a lead is created, with or without a last name', async () => {
    const { id } = await api().leads.create({ values: olivia });
    expect(await fullNameOf(id)).toBe('Olivia Nguyen');
    const single = await api().leads.create({
      values: { firstName: 'Cher', mobile: '0422 222 222' },
    });
    expect(await fullNameOf(single.id)).toBe('Cher');
  });

  it('follows every change to the first or last name', async () => {
    const { id } = await api().leads.create({ values: olivia });
    await api().leads.update({ id, values: { ...olivia, lastName: 'Chen' } });
    expect(await fullNameOf(id)).toBe('Olivia Chen');
    await api().leads.update({ id, values: { ...olivia, firstName: 'Liv', lastName: 'Chen' } });
    expect(await fullNameOf(id)).toBe('Liv Chen');
    await api().leads.update({ id, values: { ...olivia, firstName: 'Liv', lastName: '' } });
    expect(await fullNameOf(id)).toBe('Liv');
  });

  it('ignores a full name sent to create or update, so the first and last name win', async () => {
    const sneaky = { ...olivia, fullName: 'Someone Else' } as LeadInput;
    const { id } = await api().leads.create({ values: sneaky });
    expect(await fullNameOf(id)).toBe('Olivia Nguyen');
    await api().leads.update({ id, values: { ...sneaky, lastName: 'Chen' } });
    expect(await fullNameOf(id)).toBe('Olivia Chen');
  });

  it('is refused by the database when written directly', async () => {
    const { id } = await api().leads.create({ values: olivia });
    await expect(
      db.execute(sql`update leads set full_name = 'Hand Written' where id = ${id}`),
    ).rejects.toThrow();
    await expect(
      db.execute(
        sql`insert into leads (first_name, full_name, mobile) values ('A', 'Hand Written', '+61411111111')`,
      ),
    ).rejects.toThrow();
    expect(await fullNameOf(id)).toBe('Olivia Nguyen');
  });

  it('is never part of the values the app writes for a lead', () => {
    const parsed = leadRowInput();
    expect(Object.keys(leadRow(parsed))).not.toContain('fullName');
    expect(Object.keys(leadRow(parsed))).toEqual(expect.arrayContaining(['firstName', 'lastName']));
  });
});

function leadRowInput() {
  return {
    firstName: 'Olivia',
    lastName: 'Nguyen',
    email: null,
    extraEmails: [],
    mobile: null,
    secondaryMobile: null,
    streetAddress: null,
    suburb: null,
    state: null,
    postcode: null,
    source: null,
    status: 'New',
    ownerUserId: null,
    notes: null,
  } satisfies Parameters<typeof leadRow>[0];
}
